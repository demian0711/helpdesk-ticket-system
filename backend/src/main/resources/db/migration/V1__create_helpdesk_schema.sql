CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(16) NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_not_blank CHECK (btrim(email) <> ''),
    CONSTRAINT ck_users_password_hash_not_blank CHECK (btrim(password_hash) <> ''),
    CONSTRAINT ck_users_role CHECK (role IN ('REQUESTER', 'AGENT', 'ADMIN'))
);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    priority VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    requester_id BIGINT NOT NULL REFERENCES users (id),
    assignee_id BIGINT REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_tickets_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT ck_tickets_description_not_blank CHECK (btrim(description) <> ''),
    CONSTRAINT ck_tickets_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_tickets_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED')),
    CONSTRAINT ck_tickets_assignee_required_after_open CHECK (status = 'OPEN' OR assignee_id IS NOT NULL)
);

CREATE INDEX ix_tickets_requester_updated ON tickets (requester_id, updated_at DESC, id DESC);
CREATE INDEX ix_tickets_assignee_updated ON tickets (assignee_id, updated_at DESC, id DESC);
CREATE INDEX ix_tickets_status_updated ON tickets (status, updated_at DESC, id DESC);

CREATE TABLE ticket_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets (id),
    author_id BIGINT NOT NULL REFERENCES users (id),
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ticket_comments_body_not_blank CHECK (btrim(body) <> '')
);

CREATE INDEX ix_ticket_comments_timeline ON ticket_comments (ticket_id, created_at, id);

CREATE TABLE ticket_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets (id),
    actor_id BIGINT NOT NULL REFERENCES users (id),
    event_type VARCHAR(24) NOT NULL,
    old_assignee_id BIGINT REFERENCES users (id),
    new_assignee_id BIGINT REFERENCES users (id),
    old_status VARCHAR(16),
    new_status VARCHAR(16),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ticket_events_payload CHECK (
        (
            event_type = 'ASSIGNMENT_CHANGED'
            AND new_assignee_id IS NOT NULL
            AND old_assignee_id IS DISTINCT FROM new_assignee_id
            AND old_status IS NULL
            AND new_status IS NULL
        ) OR (
            event_type = 'STATUS_CHANGED'
            AND old_assignee_id IS NULL
            AND new_assignee_id IS NULL
            AND old_status IS NOT NULL
            AND new_status IS NOT NULL
            AND (
                (old_status = 'OPEN' AND new_status = 'IN_PROGRESS')
                OR (old_status = 'IN_PROGRESS' AND new_status = 'RESOLVED')
            )
        )
    )
);

CREATE INDEX ix_ticket_events_timeline ON ticket_events (ticket_id, created_at, id);
